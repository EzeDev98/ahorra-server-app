CREATE TABLE behavior_baselines (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id            BIGINT        NOT NULL,
    category_id        BIGINT        NOT NULL,
    window_days        INT           NOT NULL,
    day_type           VARCHAR(10)   NOT NULL,
    mean_amount        NUMERIC(19,2) NOT NULL,
    std_dev            NUMERIC(19,2) NOT NULL,
    sample_days        INT           NOT NULL,
    confidence         NUMERIC(4,3) NOT NULL,
    computed_through   DATE          NOT NULL,
    updated_at         TIMESTAMP,
    CONSTRAINT uq_behavior_baseline UNIQUE (user_id, category_id, window_days, day_type),
    CONSTRAINT ck_baseline_window CHECK (window_days > 0),
    CONSTRAINT ck_baseline_day_type CHECK (day_type IN ('ALL', 'WEEKDAY', 'WEEKEND')),
    CONSTRAINT ck_baseline_confidence CHECK (confidence >= 0 AND confidence <= 1),
    CONSTRAINT ck_baseline_samples CHECK (sample_days >= 0)
);

CREATE INDEX idx_behavior_baselines_user ON behavior_baselines (user_id);

CREATE TABLE detected_habits (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             BIGINT        NOT NULL,
    category_id         BIGINT        NOT NULL,
    description         VARCHAR(500) NOT NULL,
    first_observed      DATE          NOT NULL,
    last_observed       DATE          NOT NULL,
    frequency_per_week NUMERIC(5,2) NOT NULL,
    avg_amount          NUMERIC(19,2) NOT NULL,
    trend_direction     VARCHAR(10)   NOT NULL,
    confidence          NUMERIC(4,3) NOT NULL,
    status              VARCHAR(10)   NOT NULL,
    updated_at          TIMESTAMP,
    CONSTRAINT uq_detected_habit UNIQUE (user_id, category_id),
    CONSTRAINT ck_habit_trend CHECK (trend_direction IN ('STABLE', 'WORSENING', 'IMPROVING')),
    CONSTRAINT ck_habit_status CHECK (status IN ('ACTIVE', 'LAPSED')),
    CONSTRAINT ck_habit_confidence CHECK (confidence >= 0 AND confidence <= 1)
);

CREATE INDEX idx_detected_habits_user ON detected_habits (user_id);